#!/usr/bin/env python3
"""Ars Grammatica: write recitation-quick.js (the Quick recitations for the Recitation Tablet).

Usage:
  python3 tools/integrate-quick.py [--dry-run] [--input FILE] [--cardmap FILE] [deckId ...]
      default input:   /workspace/deck-split-grammatica/quick-drafts/quick-all.json
      default cardmap: /workspace/deck-split-grammatica/cardmap.json (optional; used for the card coverage check)
      --dry-run (or --validate): check everything and report, write nothing.
      deckId ...: integrate only these decks (default: every deck in the input).

Input format (the Editor's quick-all.json, as in Ars Logica):
  { "<deck id>": { "quick": [ {"html": "...", "from": [3, 4], "verbatim": false, "card": 2 or [2, 3]}, ... ],
                   "leftOut": [5, 6], "leftOutReasons": {"5": "..."} }, ... }
  A bare list of lines, or lines given as plain strings, is accepted too. "from" holds 1-based numbers of the deck's
  Full lines (the `recitation` array in data/decks/<id>.js). Keys starting "section" are skipped: whole sections
  have only their Full recitation.

Checks (a failing deck is not written unless --force):
  every word of a Quick line comes from its source Full lines, or is a joining word (and, both, but, so, or);
  no dashes; source numbers valid and in Full order; card field matches the cards of its sources and every card
  that has a Full line is covered (only when a cardmap is given); about 10 to 12 lines; at least 80 words in all.
Each line is written as {html, card, from}: html is shown in the tablet; card and from are notes for editors.
Decks already in recitation-quick.js are kept unless the input supplies them again; decks no longer in data/structure.js are dropped. A deck with no entry shows Full only.
"""
import json, os, re, subprocess, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, 'recitation-quick.js')
JOIN = {'and', 'both', 'but', 'so', 'or'}
HEAD = ("'use strict';\n/* Quick recitations for the Recitation Tablet: about ten to twelve core claims for each deck.\n"
        "   Quick is offered first; the Full recitation (each deck's recitation field in data/decks) opens once the student presses \"Done\" on Quick.\n"
        "   A deck not listed here has only its Full recitation, as before. Empty until Timothy approves the lines.\n"
        "   Generated by tools/integrate-quick.py; see notes/QUICK-RECITATIONS.md. */\n")

def current():
    if not os.path.exists(OUT): return {}
    m = re.search(r'/\*DATA\*/(.*)/\*END\*/', open(OUT, encoding='utf8').read(), re.S)
    return json.loads(m.group(1)) if m else {}

def full_lines():
    js = ("const fs=require('fs'),vm=require('vm');global.window=global;global.ARS={};const R=process.argv[1];"
          "for(const f of fs.readdirSync(R+'/data/decks'))if(f.endsWith('.js'))vm.runInThisContext(fs.readFileSync(R+'/data/decks/'+f,'utf8'));"
          "const o={};for(const[k,d]of Object.entries(ARS.decks))o[k]=Array.isArray(d.recitation)?d.recitation:[];"
          "process.stdout.write(JSON.stringify(o));")
    return json.loads(subprocess.run(['node', '-e', js, ROOT], capture_output=True, text=True, check=True).stdout)

def order():
    src = open(os.path.join(ROOT, 'data/structure.js'), encoding='utf8').read()
    return re.findall(r"\{\s*id:'([a-z]+\.[a-z0-9-]+)'", src)

def words(h):
    t = re.sub(r'<[^>]+>', ' ', h).lower().replace('\u2019', "'")
    return re.findall(r"[^\W_]+(?:'[^\W_]+)?", t)

def check(deck, lines, full, cm):
    probs = []
    F = full.get(deck)
    if F is None: return ['not a deck in data/decks']
    if not F: probs.append('deck has no Full recitation')
    if not (10 <= len(lines) <= 12) and not (len(F) <= 12 and len(lines) < len(F)):
        probs.append('%d lines (expected about 10 to 12)' % len(lines))
    C = (cm or {}).get(deck, {}).get('card')
    cov = set(); prev = 0
    for k, l in enumerate(lines, 1):
        h = l.get('html', '')
        if re.search(r'[\u2013\u2014]|\s-\s', re.sub(r'<[^>]+>', '', h)): probs.append('Q%d: dash' % k)
        src = l.get('from')
        if not isinstance(src, list) or not src or any(not isinstance(x, int) or not 1 <= x <= len(F) for x in src):
            probs.append('Q%d: bad or missing "from" %r' % (k, src)); continue
        if src != sorted(src) or src[0] < prev: probs.append('Q%d: not in Full order' % k)
        prev = src[0]
        pool = {w for x in src for w in words(F[x - 1])} | JOIN
        extra = sorted(set(words(h)) - pool)
        if extra: probs.append('Q%d: words not in its source lines %s' % (k, extra))
        if C and len(C) == len(F):
            cs = sorted({C[x - 1] for x in src}); cov |= set(cs)
            card = l.get('card'); card = card if isinstance(card, list) else [card]
            if card != cs: probs.append('Q%d: card %r but sources are on %r' % (k, l.get('card'), cs))
    if C and len(C) == len(F):
        miss = sorted(set(C) - cov)
        if miss: probs.append('cards not covered %s' % miss)
    elif cm is not None: probs.append('no usable card map for this deck (coverage not checked)')
    n = sum(len(re.sub(r'<[^>]+>', ' ', l.get('html', '')).split()) for l in lines)
    if n < 80: probs.append('only %d words in all (under 80)' % n)
    return probs

def main():
    a = sys.argv[1:]
    dry = '--dry-run' in a or '--validate' in a; force = '--force' in a
    def opt(name, dflt):
        if name in a: i = a.index(name); v = a[i + 1]; del a[i:i + 2]; return v
        return dflt
    src = opt('--input', '/workspace/deck-split-grammatica/quick-drafts/quick-all.json')
    cmp = opt('--cardmap', '/workspace/deck-split-grammatica/cardmap.json')
    only = [x for x in a if not x.startswith('--')]
    if not os.path.exists(src): print('no input file yet: ' + src); return 1
    data = json.load(open(src, encoding='utf8'))
    if not isinstance(data, dict): print('input must be an object keyed by deck id'); return 1
    data = {k.strip(): v for k, v in data.items() if not k.strip().lower().startswith('section')}
    if only: data = {k: v for k, v in data.items() if k in only}
    cm = json.load(open(cmp, encoding='utf8')) if os.path.exists(cmp) else None
    full = full_lines(); ids = order(); out = current(); bad = 0
    for deck, rec in data.items():
        raw = rec if isinstance(rec, list) else (rec or {}).get('quick') or []
        raw = [{'html': q} if isinstance(q, str) else q for q in raw]
        lines = [q for q in raw if isinstance(q, dict) and (q.get('html') or '').strip()]
        if not lines: print('skip %s: no lines' % deck); continue
        probs = check(deck, lines, full, cm)
        for p in probs: print('  %s: %s' % (deck, p))
        if probs: bad += 1
        print(('FAIL ' if probs else 'ok   ') + '%s: %d lines' % (deck, len(lines)))
        if not probs or force:
            out[deck] = [{k: q[k] for k in ('html', 'card', 'from') if k in q} for q in lines]
    missing = [d for d in full if full[d] and d not in data and d in ids]
    print('%d decks in input, %d with problems; %d decks with a Full recitation have no Quick draft' % (len(data), bad, len(missing)))
    if dry: print('dry run: nothing written'); return 1 if bad else 0
    gone = sorted(k for k in out if k not in ids)
    if gone: print('dropped (no longer in data/structure.js): ' + ', '.join(gone))
    keys = sorted((k for k in out if k in ids), key=ids.index)
    with open(OUT, 'w', encoding='utf8') as f:
        f.write(HEAD + 'window.__arsQuickRecitations = /*DATA*/' + json.dumps({k: out[k] for k in keys}, ensure_ascii=False, indent=2) + '/*END*/;\n')
    print('wrote %s (%d decks)' % (OUT, len(out)))
    return 1 if bad else 0

if __name__ == '__main__':
    sys.exit(main())
